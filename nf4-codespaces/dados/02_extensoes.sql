USE loja_cerrado;
-- Sem inventar colunas no esquema original: extensões identificadas.
ALTER TABLE PEDIDO MODIFY pid INT NOT NULL AUTO_INCREMENT;
ALTER TABLE PEDIDO AUTO_INCREMENT=1000;
CREATE TABLE PRECO_ATUAL (
 rid INT PRIMARY KEY, preco DECIMAL(10,2) NOT NULL CHECK(preco>=0),
 FOREIGN KEY(rid) REFERENCES PRODUTO(rid)
);
INSERT INTO PRECO_ATUAL VALUES (10,150),(20,80),(30,600),(40,900),(50,450);
CREATE TABLE REQUISICAO (
 cid INT NOT NULL, chave VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
 resumo CHAR(64) NOT NULL, pid INT NOT NULL,
 PRIMARY KEY(cid,chave), UNIQUE(pid), FOREIGN KEY(pid) REFERENCES PEDIDO(pid)
);
CREATE TABLE OUTBOX (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, pid INT NOT NULL UNIQUE,
 estado ENUM('PENDENTE','PROCESSANDO','ENVIADO','MORTO') NOT NULL DEFAULT 'PENDENTE',
 tentativas INT NOT NULL DEFAULT 0, proxima DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 lease_ate DATETIME(6), dono CHAR(36), erro VARCHAR(40),
 FOREIGN KEY(pid) REFERENCES PEDIDO(pid), INDEX(estado,proxima)
);
CREATE TABLE COBRANCA_SIMULADA (
 evento_id BIGINT PRIMARY KEY, pid INT NOT NULL UNIQUE,
 valor DECIMAL(12,2) NOT NULL, estado ENUM('APROVADO','RECUSADO') NOT NULL,
 criado_em DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
);
CREATE TABLE AUDITORIA (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, ator VARCHAR(30) NOT NULL,
 acao VARCHAR(60) NOT NULL, recurso INT, instante DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6)
);
